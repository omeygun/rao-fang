"""Evaluate the student on the HUMAN test set only (spec §8.3, §16.5) → docs/eval.md.

human_test.jsonl is never used for training or threshold tuning. Every metric is printed
with its n; groups with n < 30 are labelled "n < 30: indicative only" and no conclusions
are drawn from them (the generated text says so explicitly).
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

from embedder import get_embedder
from metrics import SMALL_N, SMALL_N_LABEL, aspect_scores, coverage_precision, fmt, n_label, sentiment_accuracy, top_errors
from schema import validate_row
from student import DATA, STUDENT_PATH, Student, load_jsonl

DOCS = Path(__file__).parent.parent / "docs"

TODO = """# Evaluation — human test set

**TODO [MANUAL] — no numbers yet.** This file is generated by `ml/eval.py` and is
overwritten when it runs. It needs:

1. `ml/data/human_test.jsonl` — feedback written by people (not by Claude), labeled by people.
   Format and instructions: `ml/data/human_test.template.jsonl` and `ml/data/README.md`.
2. A trained student: `python ml/train_student.py` (needs `ml/data/synthetic.jsonl`).

Then run `python ml/eval.py`. No evaluation numbers have been produced yet; none are claimed anywhere.
"""


def block(rows, preds):
    return {"aspects": aspect_scores(rows, preds), "sentiment": sentiment_accuracy(rows, preds), "coverage": coverage_precision(rows, preds)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", default=str(DATA / "human_test.jsonl"))
    ap.add_argument("--student", default=str(STUDENT_PATH))
    ap.add_argument("--out", default=str(DOCS / "eval.md"))
    ap.add_argument("--fake-embedder", action="store_true", help="smoke test only; writes to stdout, never to docs/")
    args = ap.parse_args()

    if not Path(args.test).exists() or not Path(args.student).exists():
        missing = [p for p in (args.test, args.student) if not Path(p).exists()]
        print(f"missing: {missing}; writing TODO to {args.out}", file=sys.stderr)
        if not args.fake_embedder:
            Path(args.out).write_text(TODO)
        sys.exit(1)

    rows = load_jsonl(Path(args.test))
    bad = [(r.get("id"), e) for r in rows if (e := validate_row(r))]
    if bad:
        sys.exit(f"invalid rows in test set: {bad[:5]}")
    if any(r.get("source", "").startswith("synthetic") for r in rows):
        sys.exit("human_test.jsonl contains synthetic rows — the test set must be human-written")

    student = Student.load(Path(args.student))
    if student.meta.get("fake_embedder") != args.fake_embedder:
        sys.exit("embedder mismatch between student and this run")
    emb = get_embedder(args.fake_embedder)
    preds = student.predict(rows, emb)

    langs = sorted({r["lang"] for r in rows})
    groups = {l: [i for i, r in enumerate(rows) if r["lang"] == l] for l in langs}
    res = {"overall": block(rows, preds)} | {l: block([rows[i] for i in ix], [preds[i] for i in ix]) for l, ix in groups.items()}

    dev_path = Path(args.student).parent / "student_dev_report.json"
    dev = json.loads(dev_path.read_text()) if dev_path.exists() else None

    L = []
    L.append("# Evaluation — human test set\n")
    L.append(f"Generated by `ml/eval.py` on {time.strftime('%Y-%m-%d %H:%M')}. Test file: `{Path(args.test).name}` "
             f"(human-written, never used for training or threshold tuning). Student trained on `{student.meta.get('data')}` "
             f"(n_train={student.meta.get('n_train')}), thresholds tau_lo={student.tau_lo}, tau_hi={student.tau_hi} (tuned on the synthetic dev split).\n")
    if args.fake_embedder:
        L.append("> ⚠️ FAKE EMBEDDER SMOKE TEST — numbers are meaningless.\n")
    L.append(f"Groups with n < {SMALL_N} are labelled **{SMALL_N_LABEL}**. No conclusions are drawn from them: "
             "no claim that one language is better or worse, and no claim that the model works for that group.\n")

    L.append("## Aspects and sentiment\n")
    L.append("| Group | n items | Aspect micro-F1 | Aspect macro-F1 | Micro P | Micro R | Sentiment acc. (n pairs) |")
    L.append("|---|---|---|---|---|---|---|")
    for name, b in res.items():
        a, s = b["aspects"], b["sentiment"]
        L.append(f"| {name} | {n_label(a['n'])} | {fmt(a['micro_f1'])} | {fmt(a['macro_f1'])} | {fmt(a['micro_p'])} | {fmt(a['micro_r'])} | "
                 f"{fmt(s['accuracy'])} ({n_label(s['n_pairs'])}) |")
    L.append("\nAspect F1 is computed on all items (as if no item were sent to the “not sure” queue). "
             "Sentiment accuracy is over (item, aspect) pairs where the aspect is both predicted and in the gold labels.\n")

    L.append("## Coverage vs. precision at the chosen thresholds\n")
    L.append("Coverage = share of items the tool classifies itself (not sent to “ไม่แน่ใจ / not sure”). "
             "Precision-when-sure = aspect precision on those items only.\n")
    L.append("| Group | n items | n auto-classified | Coverage | Precision when sure | Exact match when sure | “Not sure” reasons |")
    L.append("|---|---|---|---|---|---|---|")
    for name, b in res.items():
        c = b["coverage"]
        L.append(f"| {name} | {n_label(c['n'])} | {c['n_covered']} | {fmt(c['coverage'])} | {fmt(c['precision_when_sure'])} | "
                 f"{fmt(c['exact_match_when_sure'])} | {', '.join(f'{k}: {v}' for k, v in sorted(c['unsure_reasons'].items())) or '—'} |")

    L.append("\n## Per-aspect F1 (overall)\n")
    L.append("| Aspect | support (n) | F1 |")
    L.append("|---|---|---|")
    for a, v in res["overall"]["aspects"]["per_aspect"].items():
        L.append(f"| {a} | {n_label(v['support'])} | {fmt(v['f1'])} |")

    L.append("\n## Most frequent error types (overall)\n")
    errs = top_errors(rows, preds)
    L += [f"- {e}: {c}" for e, c in errs] or ["- none"]

    L.append("\n## Synthetic dev vs. human test gap\n")
    if dev:
        dn, hn = dev["overall"]["aspects"]["n"], res["overall"]["aspects"]["n"]
        L.append("| Split | n items | Aspect micro-F1 | Coverage | Precision when sure |")
        L.append("|---|---|---|---|---|")
        L.append(f"| synthetic dev (Claude-written) | {n_label(dn)} | {fmt(dev['overall']['aspects']['micro_f1'])} | {fmt(dev['overall']['coverage']['coverage'])} | {fmt(dev['overall']['coverage']['precision_when_sure'])} |")
        L.append(f"| human test | {n_label(hn)} | {fmt(res['overall']['aspects']['micro_f1'])} | {fmt(res['overall']['coverage']['coverage'])} | {fmt(res['overall']['coverage']['precision_when_sure'])} |")
        if hn < SMALL_N:
            L.append(f"\nThe human test set has n = {hn} < {SMALL_N}: the gap is shown for transparency only and is **not** interpreted.")
        else:
            d = (res["overall"]["aspects"]["micro_f1"] or 0) - (dev["overall"]["aspects"]["micro_f1"] or 0)
            L.append(f"\nStated plainly: micro-F1 on human-written feedback is {fmt(abs(d))} {'lower' if d < 0 else 'higher'} than on "
                     "Claude-written dev data. The dev number measures how well the student imitates the teacher on teacher-written text; "
                     "the human number is the one to quote.")
    else:
        L.append("No `student_dev_report.json` found next to the student; run `ml/train_student.py`.")

    L.append("\n## Sample sizes\n")
    for l in langs:
        n = len(groups[l])
        L.append(f"- {l}: n = {n}" + (f" — ⚠️ {SMALL_N_LABEL}" if n < SMALL_N else ""))
    text = "\n".join(L) + "\n"
    if args.fake_embedder:
        print(text)
    else:
        Path(args.out).write_text(text)
        print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
