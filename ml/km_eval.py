"""Kham Mueang normalisation, before / after (spec §8.4, §16.5) → docs/km_eval.md.

Held-out pairs (≥ 20%, chosen by a stable hash of the pair id) are NEVER added to the
dictionary. The dictionary is built only from the remaining pairs:
word-mode pairs (km → th), sentence-swap aligned word pairs, and single-word helper pairs.

chrF (sacrebleu) of raw Kham Mueang vs. the Thai reference, and of dictionary-normalised
Kham Mueang vs. the same reference. n is shown next to every number.

  python km_eval.py                                  # uses data/km_pairs.jsonl
  python km_eval.py --from-export raofang-export.json  # convert an app export first
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

from km_normalize import normalize_km
from metrics import SMALL_N, SMALL_N_LABEL, n_label

DATA = Path(__file__).parent / "data"
DOCS = Path(__file__).parent.parent / "docs"
TODO = """# Kham Mueang normalisation — before / after

**TODO [MANUAL] — no numbers yet.** Generated by `ml/km_eval.py`; overwritten when it runs.

Needs `ml/data/km_pairs.jsonl`: Kham Mueang ↔ Central Thai pairs from Noor's family, collected with
the app's Teach Mode (Settings → export, then `python ml/km_eval.py --from-export <file>.json`) or written
by hand following `ml/data/km_pairs.template.jsonl`. At least 20% of pairs are held out and never enter
the dictionary. No numbers have been produced yet; none are claimed anywhere.
"""


def held_out(pid: str, frac: float) -> bool:
    return int(hashlib.sha256(pid.encode()).hexdigest()[:8], 16) / 0xFFFFFFFF < frac


def from_export(path: Path) -> list[dict]:
    j = json.loads(path.read_text())
    rows = []
    for p in j.get("km_pairs", []):
        r = {"id": p["id"], "mode": p["mode"], "km": p["km"], "th": p["th"], "source": "app-teach-mode"}
        if p.get("wordPair"):
            r["wordPair"] = p["wordPair"]
        rows.append(r)
    return rows


def build_dict(pairs: list[dict]) -> dict[str, str]:
    d = {}
    for p in pairs:
        if p["mode"] == "word":
            d[p["km"].strip()] = p["th"].strip()
        elif p["mode"] == "swap" and p.get("wordPair"):
            d[p["wordPair"]["km"].strip()] = p["wordPair"]["th"].strip()
        elif p["mode"] == "helper" and " " not in p["km"].strip() and " " not in p["th"].strip():
            d[p["km"].strip()] = p["th"].strip()
    return {k: v for k, v in d.items() if k}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pairs", default=str(DATA / "km_pairs.jsonl"))
    ap.add_argument("--from-export", help="app export JSON; converted into --pairs first")
    ap.add_argument("--holdout", type=float, default=0.25)
    ap.add_argument("--out", default=str(DOCS / "km_eval.md"))
    args = ap.parse_args()
    import sacrebleu

    if args.from_export:
        rows = from_export(Path(args.from_export))
        Path(args.pairs).write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows))
        print(f"wrote {len(rows)} pairs to {args.pairs}")
    if not Path(args.pairs).exists():
        Path(args.out).write_text(TODO)
        sys.exit(f"{args.pairs} not found; wrote TODO to {args.out}")
    pairs = [json.loads(l) for l in Path(args.pairs).read_text().splitlines() if l.strip()]
    assert args.holdout >= 0.2, "spec: hold out at least 20%"
    test = [p for p in pairs if held_out(p["id"], args.holdout)]
    train = [p for p in pairs if not held_out(p["id"], args.holdout)]
    d = build_dict(train)
    leak = [p["km"] for p in test if p["mode"] == "word" and p["km"] in d]
    print(f"{len(pairs)} pairs → dictionary from {len(train)} ({len(d)} entries), held out {len(test)}; "
          f"{len(leak)} held-out words also taught elsewhere (kept: same word taught twice)")

    def evaluate(rows):
        hyp_raw = [r["km"] for r in rows]
        hyp_norm = [normalize_km(r["km"], d)[0] for r in rows]
        refs = [[r["th"] for r in rows]]
        km_tok = covered = 0
        changed = 0
        for r, n in zip(rows, hyp_norm):
            _, toks = normalize_km(r["km"], d)
            km_tok += sum(1 for k, t in toks if k != "other")
            covered += sum(1 for k, t in toks if k == "km")
            changed += n != r["km"]
        return {
            "n": len(rows),
            "chrf_raw": sacrebleu.corpus_chrf(hyp_raw, refs).score if rows else None,
            "chrf_norm": sacrebleu.corpus_chrf(hyp_norm, refs).score if rows else None,
            "token_coverage": covered / km_tok if km_tok else None,
            "n_tokens": km_tok,
            "items_changed": changed,
        }

    groups = {"all held-out": test} | {f"mode={m}": [p for p in test if p["mode"] == m] for m in sorted({p["mode"] for p in test})}
    res = {k: evaluate(v) for k, v in groups.items() if v}
    f = lambda x: "—" if x is None else f"{x:.1f}"
    L = ["# Kham Mueang normalisation — before / after\n",
         f"Generated by `ml/km_eval.py` on {time.strftime('%Y-%m-%d %H:%M')}. {len(pairs)} pairs in `{Path(args.pairs).name}`; "
         f"dictionary built from {len(train)} pairs ({len(d)} entries); {len(test)} pairs held out by hash (fraction {args.holdout}) "
         "and never added to the dictionary.\n",
         f"Groups with n < {SMALL_N} are labelled **{SMALL_N_LABEL}** and no conclusion is drawn from them "
         "(in particular, no claim that normalisation helps or hurts).\n",
         "| Group | n pairs | chrF before (raw Kham Mueang vs Thai) | chrF after (normalised vs Thai) | Tokens covered by dictionary (n tokens) | Items changed |",
         "|---|---|---|---|---|---|"]
    for k, r in res.items():
        cov = "—" if r["token_coverage"] is None else f"{100 * r['token_coverage']:.1f}%"
        L.append(f"| {k} | {n_label(r['n'])} | {f(r['chrf_raw'])} | {f(r['chrf_norm'])} | {cov} ({r['n_tokens']}) | {r['items_changed']} |")
    L += ["", "Notes:",
          "- Speakers: a few people from one family/area; spelling of Kham Mueang in Thai script is improvised. Not representative of Northern Thai variation.",
          "- Word-mode pairs are single words, so their chrF mostly measures whether the word was taught elsewhere; sentence pairs (swap/helper) are the meaningful rows.",
          "- Token segmentation for coverage uses PyThaiNLP `newmm`; the app uses `Intl.Segmenter('th')`. Replacement logic is identical (shared test cases)."]
    if res and res["all held-out"]["n"] < SMALL_N:
        L.append(f"- ⚠️ Overall n = {res['all held-out']['n']} < {SMALL_N}: these numbers are indicative only.")
    Path(args.out).write_text("\n".join(L) + "\n")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
